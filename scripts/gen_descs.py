#!/usr/bin/env python3
"""Generate sdc_descs.js: passive / mutation / bane descriptions for the
character sheet's tap-to-describe chips, from a crawl source checkout.

    python3 scripts/gen_descs.py <crawl-ref/source> [out.js]

Statuses need no data here: webtiles already sends each status light's
description with the player message. Re-run after bumping the crawl commit.
"""
import json
import os
import re
import sys

STR = re.compile(r'"((?:[^"\\]|\\.)*)"')


def unescape(s):
    return s.encode("utf-8").decode("unicode_escape").encode("latin-1").decode("utf-8")


def read_db(path, suffix):
    """dat/descript file -> {key without suffix (lowercase): body}."""
    out = {}
    with open(path, encoding="utf-8") as f:
        chunks = f.read().split("%%%%")
    for chunk in chunks:
        lines = [l for l in chunk.strip("\n").split("\n") if not l.startswith("#")]
        while lines and not lines[0].strip():
            lines.pop(0)
        if not lines:
            continue
        key = lines[0].strip().lower()
        if not key.endswith(" " + suffix):
            continue
        body = "\n".join(lines[1:]).strip()
        # unwrap hard line breaks, keep paragraphs
        body = "\n\n".join(re.sub(r"\s*\n\s*", " ", p).strip()
                           for p in re.split(r"\n\s*\n", body) if p.strip())
        if body:
            out[key[: -len(suffix) - 1]] = body
    return out


def block(text, start):
    """The balanced {...} starting at text[start] (== '{')."""
    depth = 0
    i = start
    in_str = False
    while i < len(text):
        c = text[i]
        if in_str:
            if c == "\\":
                i += 1
            elif c == '"':
                in_str = False
        elif c == '"':
            in_str = True
        elif c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return text[start + 1 : i]
        i += 1
    raise ValueError("unbalanced")


def strings(chunk):
    """C string literals in chunk, adjacent literals concatenated."""
    out = []
    parts = re.split(r",(?=(?:[^\"]*\"[^\"]*\")*[^\"]*$)", chunk)
    for p in parts:
        lits = STR.findall(p)
        if lits:
            out.append(unescape("".join(lits)))
    return out


def read_mut_levels(path):
    """mutation-data.h -> {short name: [level 1 text, ...]}."""
    with open(path, encoding="utf-8") as f:
        src = f.read()
    out = {}
    for m in re.finditer(r"\n\{ MUT_\w+,", src):
        body = block(src, m.start() + 1)
        name = STR.search(body)
        if not name:
            continue
        rest = body[name.end():]
        b = rest.find("{")
        if b < 0:
            continue
        have = [re.sub(r"<[^>]*>", "", s) for s in strings(block(rest, b))]
        out[unescape(name.group(1)).lower()] = have
    return out


def read_fakemuts(src):
    """Innate traits that aren't real mutations ("reduced essence", species
    fake_mutations) -> {short name: long text}."""
    out = {}
    with open(os.path.join(src, "mutation.cc"), encoding="utf-8") as f:
        cc = f.read()
    for m in re.finditer(r'result\.push_back\(\{"([^"]+)",(.*?)\}\);', cc, re.S):
        lits = STR.findall(m.group(2))
        if lits:
            out[unescape(m.group(1)).lower()] = re.sub(r"<[^>]*>", "", unescape(lits[0]))
    try:
        import yaml
    except ImportError:
        return out
    sp = os.path.join(src, "dat", "species")
    for fn in sorted(os.listdir(sp)):
        if not fn.endswith(".yaml") or fn.startswith("deprecated"):
            continue
        with open(os.path.join(sp, fn), encoding="utf-8") as f:
            y = yaml.safe_load(f) or {}
        for fm in y.get("fake_mutations") or []:
            if fm.get("short") and fm.get("long"):
                out.setdefault(fm["short"].lower(), fm["long"])
    return out


def main():
    src = sys.argv[1]
    out_path = sys.argv[2] if len(sys.argv) > 2 else "sdc_descs.js"
    d = os.path.join(src, "dat", "descript")
    data = {
        "passive": read_db(os.path.join(d, "passives.txt"), "passive"),
        "mut": read_db(os.path.join(d, "mutations.txt"), "mutation"),
        "bane": read_db(os.path.join(d, "mutations.txt"), "bane"),
        "levels": read_mut_levels(os.path.join(src, "mutation-data.h")),
        "fake": read_fakemuts(src),
    }
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by scripts/gen_descs.py from crawl's dat/descript and\n"
                "// mutation-data.h (GPL, (C) the DCSS devteam). Do not edit.\n"
                "define(")
        json.dump(data, f, ensure_ascii=False, indent=0, sort_keys=True)
        f.write(");\n")
    print(out_path, {k: len(v) for k, v in data.items()})


if __name__ == "__main__":
    main()
